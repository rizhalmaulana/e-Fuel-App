  static int getHeightByVolume(int capacity, double targetVolume) {
    if (targetVolume <= 0) {
      return 0;
    }

    final Map<int, double> selectedTable;
    if (capacity <= 5000) {
      selectedTable = table5000;
    } else {
      selectedTable = table10000;
    }

    List<int> heights = selectedTable.keys.toList()..sort();

    double maxVolume = selectedTable[heights.last] ?? 0;
    if (targetVolume >= maxVolume) {
      return heights.last;
    }

    for (int i = 0; i < heights.length - 1; i++) {
      int h1 = heights[i];
      int h2 = heights[i + 1];
      double v1 = selectedTable[h1]!;
      double v2 = selectedTable[h2]!;

      if (targetVolume >= v1 && targetVolume <= v2) {
        if ((v2 - v1) == 0) {
          return h1;
        }

        double ratio = (targetVolume - v1) / (v2 - v1);
        double interpolatedHeight = h1 + (ratio * (h2 - h1));

        return interpolatedHeight.round(); // Bulatkan ke mm terdekat
      }
    }

    int closestHeight = 0;
    double minDifference = double.maxFinite;
    selectedTable.forEach((mm, liter) {
      double diff = (liter - targetVolume).abs();
      if (diff < minDifference) {
        minDifference = diff;
        closestHeight = mm;
      }
    });

    return closestHeight;
  }

  static double getVolumeByHeight(int capacity, int heightMm) {
    final Map<int, double> selectedTable;
    if (capacity <= 5000) {
      selectedTable = table5000;
    } else if (capacity >= 10000) {
      selectedTable = table10000;
    } else {
      selectedTable = table10000;
    }

    if (selectedTable.containsKey(heightMm)) {
      return selectedTable[heightMm]!;
    }

    List<int> heights = selectedTable.keys.toList()..sort();

    for (int i = 0; i < heights.length - 1; i++) {
      int h1 = heights[i];
      int h2 = heights[i + 1];

      if (heightMm >= h1 && heightMm <= h2) {
        double v1 = selectedTable[h1]!;
        double v2 = selectedTable[h2]!;

        if ((h2 - h1) == 0) return v1;

        double ratio = (heightMm - h1) / (h2 - h1);
        return v1 + (ratio * (v2 - v1));
      }
    }

    int closestMm = heights.first;
    for (int mm in heights) {
      if ((mm - heightMm).abs() < (closestMm - heightMm).abs()) {
        closestMm = mm;
      }
    }
    return selectedTable[closestMm] ?? 0.0;
  }
